# Build the \ex<id> exercise templates note: one template per IMO26 exercise,
# with the exercise statement and the solution routes of its general template(s).
# The note contains book text, so it is written into the vault, not the repo.
#   python -I docs/imo26-coverage/exercise_templates.py "<vault>/Math/IMO26 Exercise Templates.md"
import json, re, sys
from pathlib import Path

here = Path(__file__).parent
root = here.parent.parent
sys.path.insert(0, str(here))
tcov, pcov = {}, {}
for m in ["tcov_ch1", "tcov_ch2345", "tcov_ch6789"]:
    tcov.update(__import__(m).TCOV)
for m in ["cov_ch1", "cov_ch23", "cov_ch45", "cov_ch67", "cov_ch89"]:
    pcov.update(__import__(m).COV)
ex = json.load(open(here / "ex.json", encoding="utf8"))


def parse_templates(md):
    """name -> (desc, [(label, body)]) for every `## \\name` template."""
    out, cur = {}, None
    for line in md.replace("\r\n", "\n").split("\n"):
        h = re.match(r"^##\s+\\([A-Za-z][\w.-]*)\s*(?:(?:—|–|-|:|\|)\s*(.*))?$", line)
        if h:
            cur = {"desc": (h.group(2) or "").strip(), "intro": [], "routes": []}
            out[h.group(1)] = cur
            continue
        if re.match(r"^#{1,2}\s", line):
            cur = None
            continue
        if cur is None:
            continue
        r = re.match(r"^###\s+(.+?)\s*$", line)
        if r:
            cur["routes"].append([r.group(1), []])
        elif cur["routes"]:
            cur["routes"][-1][1].append(line)
        else:
            cur["intro"].append(line)
    res = {}
    for name, t in out.items():
        intro = "\n".join(t["intro"]).strip()
        routes = [(lab, "\n".join(x for x in [intro, "\n".join(b).strip()] if x)) for lab, b in t["routes"]]
        if not routes and intro:
            routes = [(t["desc"] or name, intro)]
        res[name] = (t["desc"], routes)
    return res


general = {}
general.update(parse_templates((root / "src" / "default-templates.md").read_text(encoding="utf8")))
general.update(parse_templates((root / "src" / "imo26-templates.md").read_text(encoding="utf8")))


def clean(text):
    text = re.sub(r"\s*python cell\s*—\s*not displayed in the pdf version\.?", "", text)
    text = re.sub(r"\s+\d+ \d\. [A-Z][A-Z ?,'-]+ \d+\s+", " ", text)  # running page headers
    text = text.replace("{{", "{ {").replace("}}", "} }").replace("$", "\\$")
    return re.sub(r"\s+", " ", text).strip()


def short(text, n=90):
    s = text[:n]
    return s if len(text) <= n else s[: s.rfind(" ")] + " …"


def py_line(v):
    if v == "-":
        return ""
    names = []
    for part in v.split():
        m = re.match(r"[+?]*(\w+)(?:\[(.*)\])?", part)
        names.append(f"`\\{m.group(1)}`" + (f" ({m.group(2)})" if m.group(2) else ""))
    return f"*Compute it:* in a python code block type {', '.join(names)}."


def main(out_path):
    lines = [
        "# IMO26 exercise templates",
        "",
        "Generated by the Math Autocomplete plugin repo (`docs/imo26-coverage/exercise_templates.py`). "
        "Type `\\ex1.19` (number) or `\\ex truth table` (words from the exercise) in normal text. "
        "Each template is the exercise plus the solution routes of its general template "
        "(the `\\name` in brackets); you pick the route after the exercise.",
        "Regenerating overwrites this file: put your own edits in `Math Templates.md` instead.",
        "",
    ]
    bad = []
    for x in ex:
        eid, text = x["id"], clean(x["text"])
        names = tcov[eid].split()
        missing = [n for n in names if n not in general]
        if missing:
            bad.append((eid, missing))
            continue
        lines.append(f"## \\ex{eid} — {short(text)} [{' '.join(chr(92) + n for n in names)}]")
        # The statement goes into every route (not a shared intro) so a blank
        # line separates it from the solution in the inserted text.
        head = f"**Exercise {eid}** (IMO26 p. {x['page']}). {text}"
        p = py_line(pcov.get(eid, "-"))
        if p:
            head += "\n\n" + p
        for n in names:
            for label, body in general[n][1]:
                lines.append(f"### \\{n}: {label}")
                lines.append(head)
                lines.append("")
                lines.append(body)
                lines.append("")
    if bad:
        sys.exit(f"unknown templates: {bad}")
    Path(out_path).write_text("\n".join(lines).rstrip() + "\n", encoding="utf8")
    print(f"wrote {len(ex)} exercise templates to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(here / "IMO26 Exercise Templates.md"))
